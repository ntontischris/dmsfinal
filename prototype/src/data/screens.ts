const ACCESS_PART = /^(\S+?)(?: \((.+)\))?$/;

const parseAccess = (
  code: string,
  roles: string,
): Partial<Record<RoleId, string>> =>
  Object.fromEntries(
    roles.split(" · ").map((part) => {
      const [, short, note = ""] = ACCESS_PART.exec(part) ?? [];
      const role = ROLES.find((candidate) => candidate.short === short);
      if (!role) throw new Error(`Οθόνη ${code}: άγνωστος ρόλος «${part}»`);
      return [role.id, note];
    }),
  );

export const SCREENS: readonly Screen[] = ROWS.map(({ roles, ...row }) => ({
  ...row,
  access: parseAccess(row.code, roles),
}));

export const findScreen = (code: string): Screen | undefined =>
  SCREENS.find((screen) => screen.code === code);

export const canSee = (screen: Screen, role: RoleId): boolean =>
  role in screen.access;

export const isFinal = (screen: Screen): boolean =>
  FINAL_SCREENS.includes(screen.code);

export const screensOfSection = (letter: string): readonly Screen[] =>
  SCREENS.filter((screen) => screen.code.replace(/\d+$/, "") === letter);
