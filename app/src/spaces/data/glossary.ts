const normalize = (text: string): string =>
  text.normalize("NFC").replace(/\s+/g, " ").trim().toLocaleLowerCase("el");

const BY_TERM: ReadonlyMap<string, GlossaryEntry> = new Map(
  GLOSSARY.map((entry) => [normalize(entry.term), entry]),
);

// Το κείμενο ενός σήματος → οι όροι του γλωσσαριού που περιέχει. Η σημείωση σε παρένθεση αγνοείται
// και το « · » χωρίζει δύο όρους (π.χ. «πρόταση · Εστάλη»). Ό,τι δεν είναι όρος δεν παίρνει εξήγηση.
export const explainStatus = (text: string): readonly GlossaryEntry[] => {
  const plain = normalize(text.replace(/\([^)]*\)/g, ""));
  const whole = BY_TERM.get(plain);
  if (whole) return [whole];
  return plain.split(" · ").flatMap((part) => BY_TERM.get(part.trim()) ?? []);
};
