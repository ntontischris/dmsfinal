// Το μητρώο των οδηγών (flow-studio, prototype στο proto/flows): τα βήματα κάθε δουλειάς, ένα ανά γραμμή του Steps
// στο docs/flows/<job>/flow.md. Καθαρό αρχείο: το διαβάζει και ο browser. Οι βοηθοί πλοήγησης είναι στο flows.ts.

export interface FlowChoice {
  label: string;
  // Το βήμα (1-based) που ανοίγει η επιλογή.
  to: number;
}

export interface FlowStep {
  question: string;
  // Τι είναι ήδη συμπληρωμένο (από δεδομένα της εφαρμογής).
  preset: string;
  // Τι μένει πίσω από το «Περισσότερα».
  hidden?: string;
  // Ο σταθμός: κωδικός οθόνης, ή "queue" για αναμονή (σελίδα του οδηγού στη Σήμερα, μετά γραμμή ουράς).
  station: string;
  area: string;
  // Η διαδρομή της οθόνης του σταθμού όταν χρειάζεται id (π.χ. /app/filming/<id>): αν είμαστε ήδη εκεί, μένουμε.
  stays?: RegExp;
  // Η αποθήκευση του σταθμού στέλνει εδώ χωρίς τη θέση· ο οδηγός συνεχίζει στο επόμενο βήμα.
  landsOn?: RegExp;
  // Το βήμα διαλέγει Πελάτη μέσα στον οδηγό· η επιλογή περνά στο επόμενο βήμα ως ?client=.
  picksClient?: boolean;
  // Το κύριο κουμπί του οδηγού υποβάλλει τη φόρμα του σταθμού (μία αποθήκευση, όχι «Επόμενο» χωρίς αποθήκευση).
  submits?: { form: string; label: string };
  // Ο σταθμός ανοίγει στη μέρα του γυρίσματος (?date=), αν ο οδηγός την ξέρει.
  opensOnDate?: boolean;
  // Το κύριο κουμπί μένει κλειστό μέχρι το Γύρισμα να έχει ό,τι λέει εδώ (από τη βάση, μέσω της σελίδας του).
  requires?: readonly Need[];
  // Κουμπιά αντί για «Επόμενο»: το πρώτο είναι το κύριο, τα άλλα δευτερεύοντα.
  choices?: readonly FlowChoice[];
  // Το βήμα ανοίγει μόνο από μια επιλογή («μόνο μετά από …»)· η σειρά «Επόμενο» το προσπερνά.
  isBranch?: boolean;
  // Το επόμενο βήμα όταν δεν είναι το αμέσως επόμενο (π.χ. πίσω στο 1 για την επόμενη γραμμή).
  then?: number;
  // Ο αριθμός του βήματος όπως στο flow.md («2α», «⏳3»)· χωρίς αυτόν, η θέση του.
  mark?: string;
}

export type Need = "crew" | "equipment";

export interface Flow {
  id: string;
  name: string;
  area: string;
  done: string;
  steps: readonly FlowStep[];
  // Το όνομα της γραμμής της στο «Τι πρέπει να κάνω τώρα», αν δεν είναι το όνομα της δουλειάς.
  queueName?: string;
  // Η δουλειά γυρνά στο βήμα 1 για την επόμενη γραμμή και τελειώνει όταν δεν μένει καμία.
  isLoop?: boolean;
  // Το κουμπί που περνά στην επόμενη γραμμή.
  nextLabel?: string;
}

