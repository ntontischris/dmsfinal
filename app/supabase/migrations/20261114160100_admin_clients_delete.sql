-- Πρόσβαση a7: η Διαχείριση «Διαγράφει Πελάτες».
--
-- Ο έτοιμος Ρόλος «Διαχείριση» τρέχει την καθημερινή λειτουργία με Εύρος «όλα»· ένας Πελάτης που μπήκε κατά λάθος είναι
-- καθημερινή δουλειά, όχι απόφαση Ιδιοκτήτη. Η διαγραφή μένει περιορισμένη από την public.client_delete (μόνο Πελάτης χωρίς
-- πραγματική δουλειά ή χρήμα). Ο Ιδιοκτήτης μπορεί να το αφαιρέσει από τον Ρόλο όποτε θέλει, όπως κάθε Δικαίωμα.
insert into public.role_permissions (role_id, permission, scope)
select r.id, 'clients.delete', 'all'
  from public.roles r
 where r.name = 'Διαχείριση' and r.kind = 'team'
on conflict do nothing;
